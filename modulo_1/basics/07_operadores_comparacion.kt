fun main() {
    
    println("operadores de comparación")
    val num1=10
    val num2=2
    println("$num1 == $num2: ${num1==num2}")
    println("$num1 != $num2: ${num1!=num2}")
    println("$num1 > $num2: ${num1>num2}")
    println("$num1 < $num2: ${num1<num2}")
    println("$num1 <= $num2: ${num1<=num2}")
    println("$num1 >= $num2: ${num1>=num2}")
 }